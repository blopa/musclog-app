import {
  cpSync,
  existsSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';

type Library = {
  manifest: { faceOrder: string[]; poses: Record<string, PoseSpec> };
  part: (ref: string) => unknown;
};
type PoseSpec = {
  alternateFaces?: boolean;
  animated?: { alternateFaces?: boolean; upper?: string[] };
  face: string;
  layers: unknown[];
};

const { findStale, generateAll, loadLibrary, PARTS_DIR } =
  require('../../scripts/generate-loggy-svgs') as {
    findStale: (generated: Record<string, string>) => string[];
    generateAll: (options?: { partsDir?: string }) => Record<string, string>;
    loadLibrary: (partsDir?: string) => Library;
    PARTS_DIR: string;
  };

const generated = generateAll();
const stills = Object.entries(generated).filter(([file]) => file.includes('loggy-poses'));
const animated = Object.entries(generated).filter(([file]) => file.includes('loggy-animated'));

/** A copy of the part library to edit, so a test never touches the real parts. */
function withTemporaryParts(edit: (dir: string) => void): Record<string, string> {
  const dir = mkdtempSync(join(tmpdir(), 'loggy-parts-'));

  try {
    cpSync(PARTS_DIR, dir, { recursive: true });
    edit(dir);

    return generateAll({ partsDir: dir });
  } finally {
    rmSync(dir, { force: true, recursive: true });
  }
}

function editFile(file: string, change: (text: string) => string) {
  writeFileSync(file, change(readFileSync(file, 'utf8')));
}

/** Contents of the generated file for `pose`, `kind` being 'poses' (still) or 'animated'. */
function output(files: Record<string, string>, kind: 'animated' | 'poses', pose: string): string {
  const entry = Object.entries(files).find(([file]) =>
    file.endsWith(`loggy-${kind}/loggy-${pose}.svg`)
  );

  if (!entry) {
    throw new Error(`no generated ${kind} file for ${pose}`);
  }

  return entry[1];
}

describe('generated Loggy SVGs', () => {
  // The SVGs are committed (the app imports them, and the animated ones feed
  // `generate-loggy-animated`), so a part edited without `npm run generate-loggy` would ship stale.
  it('are up to date with the parts', () => {
    for (const [file, contents] of Object.entries(generated)) {
      expect({ file, same: readFileSync(file, 'utf8') === contents }).toEqual({
        file,
        same: true,
      });
    }
  });

  it('leave no pose SVG behind that the manifest no longer builds', () => {
    expect(findStale(generated)).toEqual([]);
  });

  it('build a still and an animated twin for every pose', () => {
    const poses = Object.keys(loadLibrary().manifest.poses);

    expect(poses.length).toBeGreaterThan(0);
    expect(stills).toHaveLength(poses.length);
    expect(animated).toHaveLength(poses.length);
  });

  it.each(stills.map(([file]) => file))('%s defines every class it uses', (file) => {
    const svg = generated[file];
    const defined = new Set([...svg.matchAll(/\.(s\d+) \{/g)].map((match) => match[1]));
    const used = new Set([...svg.matchAll(/<path class="(s\d+)"/g)].map((match) => match[1]));

    expect([...used].filter((name) => !defined.has(name))).toEqual([]);
    expect([...defined].filter((name) => !used.has(name))).toEqual([]);
  });

  it('keep the generated-file note out of the drawing, in a comment', () => {
    for (const [, svg] of Object.entries(generated)) {
      expect(svg).toMatch(/<!-- Generated by scripts\/generate-loggy-svgs\.js /);
    }
  });
});

describe('every part in the library', () => {
  const library = loadLibrary();
  const refs = readdirSync(PARTS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name !== 'animations')
    .flatMap((entry) =>
      readdirSync(join(PARTS_DIR, entry.name))
        .filter((name) => name.endsWith('.svg'))
        .map((name) => `${entry.name}/${name.replace(/\.svg$/, '')}`)
    );

  it('finds the parts', () => {
    expect(refs.length).toBeGreaterThan(50);
  });

  // Includes the parts no pose stacks yet (the pointing arm), which would otherwise only fail the
  // day someone uses them.
  it.each(refs)('%s reads as one group in palette classes', (ref) => {
    expect(() => library.part(ref)).not.toThrow();
  });

  it('has an animation sheet for every pose', () => {
    for (const pose of Object.keys(library.manifest.poses)) {
      expect(existsSync(join(PARTS_DIR, 'animations', `${pose}.css`))).toBe(true);
    }
  });
});

describe('a part is drawn once', () => {
  it('takes a face edit into every pose that has it, shown or hidden', () => {
    const files = withTemporaryParts((dir) =>
      editFile(join(dir, 'faces', 'happy.svg'), (text) =>
        text.replace(/ d="[^"]*"/, ' d="m1 2l3 4z"')
      )
    );

    // Wave shows it; every pose that keeps the alternates carries it hidden.
    expect(output(files, 'poses', 'wave')).toContain('d="m1 2l3 4z"');
    expect(output(files, 'animated', 'wave')).toContain('d="m1 2l3 4z"');
    expect(output(files, 'poses', 'default')).toContain('d="m1 2l3 4z"');
    // A pose with a single face never drew it.
    expect(output(files, 'poses', 'flex')).not.toContain('d="m1 2l3 4z"');
  });

  it('takes a torso edit into every pose that stacks it, and no other', () => {
    const files = withTemporaryParts((dir) =>
      editFile(join(dir, 'log', 'default.svg'), (text) =>
        text.replace(/ d="[^"]*"/, ' d="m5 6l7 8z"')
      )
    );
    const library = loadLibrary();
    const usesDefaultLog = (spec: PoseSpec) => JSON.stringify(spec.layers).includes('log/default');

    for (const [pose, spec] of Object.entries(library.manifest.poses)) {
      for (const kind of ['poses', 'animated'] as const) {
        expect({
          pose,
          kind,
          edited: output(files, kind, pose).includes('d="m5 6l7 8z"'),
        }).toEqual({ pose, kind, edited: usesDefaultLog(spec) });
      }
    }

    // The thinking pose keeps its own log, so the shared one's edit must not reach it.
    expect(output(files, 'poses', 'thinking')).not.toContain('d="m5 6l7 8z"');
  });

  it('takes a palette edit into every pose that uses the colour', () => {
    const files = withTemporaryParts((dir) =>
      editFile(join(dir, 'palette.css'), (text) => text.replace(/#47ad92/g, '#123456'))
    );

    for (const [file, svg] of Object.entries(files)) {
      expect({ file, hasOldGreen: svg.includes('#47ad92') }).toEqual({ file, hasOldGreen: false });
    }

    expect(output(files, 'poses', 'flex')).toContain('#123456');
  });
});

describe('a pose', () => {
  const { manifest } = loadLibrary();
  const faceCount = manifest.faceOrder.length;
  const countOf = (svg: string, pattern: RegExp) => (svg.match(pattern) ?? []).length;
  const faceGroups = (svg: string) =>
    [...svg.matchAll(/<g id="(face(?:-[a-z-]+)?)"( display="none")?>/g)].filter((match) =>
      ['face', ...manifest.faceOrder.map((name) => `face-${name}`)].includes(match[1])
    );

  it.each(Object.entries(manifest.poses))(
    '%s shows its one face, and keeps the others hidden only when asked',
    (pose, spec) => {
      const still = faceGroups(output(generated, 'poses', pose));
      const twin = faceGroups(output(generated, 'animated', pose));
      const shown = (groups: RegExpMatchArray[]) => groups.filter((match) => !match[2]);

      expect(shown(still).map((match) => match[1])).toEqual([
        spec.face === 'default' ? 'face' : `face-${spec.face}`,
      ]);
      expect(still).toHaveLength(spec.alternateFaces ? faceCount : 1);
      expect(shown(twin)).toHaveLength(1);
      expect(twin).toHaveLength(spec.animated?.alternateFaces ? faceCount : 1);
    }
  );

  it.each(animated.map(([file]) => file))('%s wraps the drawing in the idle group', (file) => {
    expect(countOf(generated[file], /<g id="loggy-idle">/g)).toBe(1);
    expect(generated[file]).toMatch(/@media \(prefers-reduced-motion: reduce\)/);
  });

  it('puts the animated "upper" run in one group, in stack order', () => {
    const wave = output(generated, 'animated', 'wave');

    expect(countOf(wave, /<g id="upper">/g)).toBe(1);
    expect(wave.indexOf('<g id="upper">')).toBeGreaterThan(wave.indexOf('<g id="leg-r">'));
    expect(wave.indexOf('<g id="arm-l">')).toBeGreaterThan(wave.indexOf('<g id="upper">'));
  });
});

describe('the build refuses a part that would draw wrongly', () => {
  const failure = (edit: (dir: string) => void) => {
    try {
      withTemporaryParts(edit);
    } catch (error) {
      return (error as Error).message;
    }

    return null;
  };

  it('says which variants exist when a pose names one that does not', () => {
    const message = failure((dir) =>
      editFile(join(dir, 'poses.json'), (text) =>
        text.replace('"leg-l/standing"', '"leg-l/missing"')
      )
    );

    expect(message).toMatch(/Unknown part "leg-l\/missing"/);
    expect(message).toMatch(/"leg-l" has: .*standing/);
  });

  it('rejects an inline fill (colours are palette classes)', () => {
    const message = failure((dir) =>
      editFile(join(dir, 'leaf', 'default.svg'), (text) =>
        text.replace('<path ', '<path fill="#ff0000" ')
      )
    );

    expect(message).toMatch(/unsupported attribute "fill"/);
  });

  it("rejects display on a part (hiding is the pose's job)", () => {
    const message = failure((dir) =>
      editFile(join(dir, 'leaf', 'default.svg'), (text) =>
        text.replace('<g id="leaf">', '<g id="leaf" display="none">')
      )
    );

    expect(message).toMatch(/unsupported attribute "display"/);
  });

  it('rejects a class the palette does not define', () => {
    const message = failure((dir) =>
      editFile(join(dir, 'leaf', 'default.svg'), (text) =>
        text.replace('class="s1"', 'class="s99"')
      )
    );

    expect(message).toMatch(/class="s99"> is not in palette\.css/);
  });

  it('rejects a face file the manifest does not list', () => {
    const message = failure((dir) =>
      writeFileSync(
        join(dir, 'faces', 'extra.svg'),
        readFileSync(join(dir, 'faces', 'happy.svg'), 'utf8').replace('face-happy', 'face-extra')
      )
    );

    expect(message).toMatch(/faces\/extra\.svg is not in "faceOrder"/);
  });

  it('rejects an "upper" run whose layers are not next to each other', () => {
    const message = failure((dir) =>
      editFile(join(dir, 'poses.json'), (text) => {
        const manifest = JSON.parse(text);

        manifest.poses.wave.animated.upper = ['arm-l', 'arm-r'];

        return JSON.stringify(manifest);
      })
    );

    expect(message).toMatch(/not next to each other/);
  });

  it('rejects two groups that share an id', () => {
    const message = failure((dir) =>
      editFile(join(dir, 'poses.json'), (text) => {
        const manifest = JSON.parse(text);

        manifest.poses.flex.layers.push('arm-l/flex');

        return JSON.stringify(manifest);
      })
    );

    expect(message).toMatch(/the id "arm-l" appears twice/);
  });
});
