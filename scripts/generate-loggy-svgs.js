/* eslint-disable no-undef */
'use strict';

/**
 * Builds every Loggy pose SVG from one library of parts, so a part is drawn once and every pose
 * that stacks it picks the change up:
 *
 *   assets/avatars/loggy-poses/loggy-<pose>.svg     the still, imported by `components/LoggyPose.tsx`
 *   assets/avatars/loggy-animated/loggy-<pose>.svg  its animated twin (`generate-loggy-animated.js`
 *                                                   turns that into a component)
 *
 * The source is `assets/avatars/loggy-parts/`:
 *
 *   palette.css        the one style sheet: `.s0 { fill: … }`. Every part names its colour by class,
 *                      and `generate-loggy-animated.js` expects the `s<number>` names.
 *   <id>/<variant>.svg one part: a single `<g id="<id>">` (nested groups, such as a foot inside a
 *                      leg, stay in the file). `leg-l/standing.svg`, `log/thinking.svg`, …
 *   faces/<name>.svg   one face: `<g id="face-<name>">` (the default face is `faces/default.svg`,
 *                      `<g id="face">`).
 *   animations/<pose>.css  the keyframes of the pose's animated twin.
 *   poses.json         what each pose stacks, bottom to top, and which face it shows.
 *
 * A part file is a plain SVG, so it opens in a browser or editor on its own (the
 * `xml-stylesheet` line pulls in the palette); only `<g id>` and `<path class d>` are allowed, and
 * this script says so when a part strays (an inline `fill`, a `style` attribute, an unknown class).
 * A part is the art only: whether it is hidden is decided by the pose, never stored in the part.
 *
 * Edit a part, then run `npm run generate-loggy` (this script, then the animated components).
 * `components/__tests__/loggyPartsGenerated.test.ts` fails when an output is stale.
 */

const fs = require('node:fs');
const path = require('node:path');

const { readAttributes } = require('./lib/svgAttributes');

const ROOT = path.join(__dirname, '..');
const AVATARS_DIR = path.join(ROOT, 'assets', 'avatars');
const PARTS_DIR = path.join(AVATARS_DIR, 'loggy-parts');
const STILL_DIR = path.join(AVATARS_DIR, 'loggy-poses');
const ANIMATED_DIR = path.join(AVATARS_DIR, 'loggy-animated');

/** Wraps the whole animated drawing; the keyframes' `prefers-reduced-motion` rule targets it. */
const IDLE_GROUP_ID = 'loggy-idle';

/** The token a pose's layer list uses where its face block goes (inside the body group). */
const FACE_TOKEN = '@face';

const PART_REF = /^([a-z0-9-]+)\/([a-z0-9-]+)$/;
const FACE_NAME = /^[a-z0-9-]+$/;

const GENERATED_NOTE =
  'Generated by scripts/generate-loggy-svgs.js from assets/avatars/loggy-parts. ' +
  'Do not edit this file: change the part, then run `npm run generate-loggy`.';

function relative(file) {
  return path.relative(ROOT, file);
}

// ─── Palette ─────────────────────────────────────────────────────────────────────────────────

/** `palette.css` as `Map<'s4', 'fill: #47ad92; stroke: #1b314d'>`, ordered by class number. */
function readPalette(partsDir) {
  const file = path.join(partsDir, 'palette.css');
  const css = fs.readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const entries = [];

  for (const [, name, body] of css.matchAll(/\.(s\d+)\s*\{([^}]*)\}/g)) {
    const declarations = body
      .split(';')
      .map((part) => part.trim())
      .filter(Boolean)
      .map((part) => {
        const colon = part.indexOf(':');

        if (colon < 1) {
          throw new Error(`${relative(file)}: ".${name}" has a malformed declaration "${part}"`);
        }

        return `${part.slice(0, colon).trim()}: ${part.slice(colon + 1).trim()}`;
      });

    if (!declarations.length) {
      throw new Error(`${relative(file)}: ".${name}" is empty`);
    }

    entries.push([name, declarations.join('; ')]);
  }

  const names = entries.map(([name]) => name);

  if (new Set(names).size !== names.length) {
    throw new Error(`${relative(file)}: a class is defined twice`);
  }

  if (!entries.length) {
    throw new Error(`${relative(file)}: no ".s<number> { … }" classes found`);
  }

  return new Map(entries.sort((a, b) => Number(a[0].slice(1)) - Number(b[0].slice(1))));
}

// ─── Reading a part ──────────────────────────────────────────────────────────────────────────

function expectOnly(attributes, allowed, where) {
  const stray = Object.keys(attributes).filter((name) => !allowed.includes(name));

  if (stray.length) {
    throw new Error(
      `${where}: unsupported attribute ${stray.map((name) => `"${name}"`).join(', ')}. ` +
        `A part has <g id> and <path class d> only: colours are palette classes, and hiding a ` +
        `part is the pose's job.`
    );
  }
}

/**
 * Parses one part file into its root group: `{ tag: 'g', id, children }` with `{ tag: 'path',
 * cls, d }` leaves. The file may carry the XML prolog, comments, a `<style>` (ignored: the palette
 * is the only style sheet) and the `<svg>` wrapper, but exactly one top-level group.
 */
function parsePart(text, file, palette) {
  const body = text
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<\?[\s\S]*?\?>/g, '')
    .replace(/<style\b[\s\S]*?<\/style>/g, '');
  const root = { children: [] };
  const stack = [root];

  for (const [, closing, tag, rawAttributes, selfClosing] of body.matchAll(
    /<(\/?)([A-Za-z][\w:-]*)((?:\s[^>]*?)?)(\/?)>/g
  )) {
    if (tag === 'svg') {
      continue;
    }

    if (tag !== 'g' && tag !== 'path') {
      throw new Error(`${relative(file)}: <${tag}> is not allowed in a part (only <g> and <path>)`);
    }

    if (closing) {
      if (stack.length < 2) {
        throw new Error(`${relative(file)}: unbalanced </${tag}>`);
      }

      stack.pop();
      continue;
    }

    const attributes = readAttributes(rawAttributes, relative(file));
    const parent = stack[stack.length - 1];

    if (tag === 'path') {
      expectOnly(attributes, ['class', 'd'], relative(file));

      if (parent === root) {
        throw new Error(`${relative(file)}: a part is one <g id>; put the <path>s inside it`);
      }

      if (!attributes.d) {
        throw new Error(`${relative(file)}: a <path> has no d`);
      }

      if (!palette.has(attributes.class)) {
        throw new Error(
          `${relative(file)}: <path class="${attributes.class}"> is not in palette.css`
        );
      }

      parent.children.push({
        tag: 'path',
        cls: attributes.class,
        d: attributes.d.replace(/\s+/g, ' ').trim(),
      });
      continue;
    }

    expectOnly(attributes, ['id'], relative(file));

    if (!/^[\w-]+$/.test(attributes.id ?? '')) {
      throw new Error(`${relative(file)}: every <g> needs a plain id`);
    }

    const node = { tag: 'g', id: attributes.id, children: [] };
    parent.children.push(node);

    if (!selfClosing) {
      stack.push(node);
    }
  }

  if (stack.length !== 1) {
    throw new Error(`${relative(file)}: a <g> is never closed`);
  }

  if (root.children.length !== 1 || root.children[0].tag !== 'g') {
    throw new Error(`${relative(file)}: a part file holds exactly one top-level <g id>`);
  }

  return root.children[0];
}

// ─── The library ─────────────────────────────────────────────────────────────────────────────

function listSvgs(dir) {
  return fs.existsSync(dir)
    ? fs
        .readdirSync(dir)
        .filter((name) => name.endsWith('.svg'))
        .map((name) => name.slice(0, -'.svg'.length))
        .sort()
    : [];
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    throw new Error(`${relative(file)}: ${error.message}`);
  }
}

/** Everything the poses are built from: the palette, the manifest and a cache of parsed parts. */
function loadLibrary(partsDir = PARTS_DIR) {
  const palette = readPalette(partsDir);
  const manifestFile = path.join(partsDir, 'poses.json');
  const manifest = readJson(manifestFile);
  const cache = new Map();

  if (!Array.isArray(manifest.faceOrder) || !manifest.poses || typeof manifest.poses !== 'object') {
    throw new Error(`${relative(manifestFile)} needs "faceOrder" (a list) and "poses" (an object)`);
  }

  const faceFiles = listSvgs(path.join(partsDir, 'faces'));
  const faceSet = new Set(manifest.faceOrder);

  if (faceSet.size !== manifest.faceOrder.length) {
    throw new Error(`${relative(manifestFile)}: "faceOrder" repeats a face`);
  }

  for (const name of manifest.faceOrder) {
    if (!FACE_NAME.test(name) || !faceFiles.includes(name)) {
      throw new Error(`${relative(manifestFile)}: face "${name}" has no faces/${name}.svg`);
    }
  }

  for (const name of faceFiles) {
    if (!faceSet.has(name)) {
      throw new Error(`faces/${name}.svg is not in "faceOrder" (${relative(manifestFile)})`);
    }
  }

  /** The parsed root group of `<dir>/<variant>`; one shared object per part, never mutated. */
  function part(ref) {
    const match = PART_REF.exec(ref);

    if (!match) {
      throw new Error(
        `"${ref}" is not a part reference (expected "<id>/<variant>", e.g. "leg-l/standing")`
      );
    }

    if (!cache.has(ref)) {
      const [, dir, variant] = match;
      const file = path.join(partsDir, dir, `${variant}.svg`);

      if (!fs.existsSync(file)) {
        const known = listSvgs(path.join(partsDir, dir));

        throw new Error(
          `Unknown part "${ref}". ${
            known.length
              ? `"${dir}" has: ${known.join(', ')}.`
              : `There is no "${dir}" folder in ${relative(partsDir)}.`
          }`
        );
      }

      cache.set(ref, parsePart(fs.readFileSync(file, 'utf8'), file, palette));
    }

    return cache.get(ref);
  }

  return { partsDir, palette, manifest, part, face: (name) => part(`faces/${name}`) };
}

// ─── Composing a pose ────────────────────────────────────────────────────────────────────────

/** The face block: the shown face, and (when asked) every other face hidden, in `faceOrder`. */
function faceNodes(library, poseName, spec, alternateFaces) {
  const { faceOrder } = library.manifest;

  if (!faceOrder.includes(spec.face)) {
    throw new Error(`Pose "${poseName}" shows face "${spec.face}", which is not in "faceOrder"`);
  }

  const nodes = [];

  for (const name of faceOrder) {
    if (name === spec.face) {
      nodes.push(library.face(name));
    } else if (alternateFaces) {
      nodes.push({ ...library.face(name), hidden: true });
    }
  }

  return nodes;
}

function expandLayer(layer, library, poseName, spec, alternateFaces) {
  if (typeof layer === 'string') {
    return layer === FACE_TOKEN
      ? faceNodes(library, poseName, spec, alternateFaces)
      : [library.part(layer)];
  }

  if (layer && typeof layer.group === 'string' && Array.isArray(layer.children)) {
    return [
      {
        tag: 'g',
        id: layer.group,
        children: layer.children.flatMap((child) =>
          expandLayer(child, library, poseName, spec, alternateFaces)
        ),
      },
    ];
  }

  throw new Error(
    `Pose "${poseName}": a layer is a part reference or { "group", "children" }, got ${JSON.stringify(layer)}`
  );
}

function walk(node, visit) {
  visit(node);

  for (const child of node.children ?? []) {
    walk(child, visit);
  }
}

/** Throws when two groups share an id: an id names one thing, and the keyframes target by id. */
function assertUniqueIds(nodes, where) {
  const seen = new Set();

  for (const node of nodes) {
    walk(node, (current) => {
      if (current.tag !== 'g') {
        return;
      }

      if (seen.has(current.id)) {
        throw new Error(`${where}: the id "${current.id}" appears twice`);
      }

      seen.add(current.id);
    });
  }
}

function usedClasses(nodes) {
  const used = new Set();

  for (const node of nodes) {
    walk(node, (current) => {
      if (current.tag === 'path') {
        used.add(current.cls);
      }
    });
  }

  return used;
}

/** Puts a contiguous run of top-level layers (named by id) in one group the keyframes can move. */
function groupRun(nodes, groupId, memberIds, poseName) {
  const wanted = new Set(memberIds);
  const indexes = nodes.flatMap((node, index) => (wanted.has(node.id) ? [index] : []));
  const found = new Set(indexes.map((index) => nodes[index].id));
  const missing = memberIds.filter((id) => !found.has(id));

  if (missing.length) {
    throw new Error(
      `Pose "${poseName}": "${groupId}" lists ${missing.join(', ')}, which are not top-level layers`
    );
  }

  const first = indexes[0];
  const last = indexes[indexes.length - 1];

  if (last - first + 1 !== indexes.length) {
    throw new Error(
      `Pose "${poseName}": the layers of "${groupId}" are not next to each other in the stack`
    );
  }

  return [
    ...nodes.slice(0, first),
    { tag: 'g', id: groupId, children: nodes.slice(first, last + 1) },
    ...nodes.slice(last + 1),
  ];
}

function serializeNode(node, depth) {
  const pad = '\t'.repeat(depth);

  if (node.tag === 'path') {
    return `${pad}<path class="${node.cls}" d="${node.d}"/>`;
  }

  const attributes = `id="${node.id}"${node.hidden ? ' display="none"' : ''}`;

  if (!node.children.length) {
    return `${pad}<g ${attributes}/>`;
  }

  return [
    `${pad}<g ${attributes}>`,
    ...node.children.map((child) => serializeNode(child, depth + 1)),
    `${pad}</g>`,
  ].join('\n');
}

function serializeDocument({ viewBox, nodes, palette, extraCss }) {
  const [, , width, height] = viewBox.split(/\s+/);
  const used = usedClasses(nodes);
  const classLines = [...palette]
    .filter(([name]) => used.has(name))
    .map(([name, declarations]) => `\t\t.${name} { ${declarations} }`);
  const css = extraCss
    ? ['', ...extraCss.split('\n').map((line) => (line.trim() ? `\t\t${line}` : ''))]
    : [];

  return [
    `<svg version="1.2" xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${width}" height="${height}">`,
    `\t<!-- ${GENERATED_NOTE} -->`,
    '\t<style>',
    ...classLines,
    ...css,
    '\t</style>',
    ...nodes.map((node) => serializeNode(node, 1)),
    '</svg>',
    '',
  ].join('\n');
}

function readViewBox(poseName, spec) {
  if (!/^-?\d+(\.\d+)?(\s+-?\d+(\.\d+)?){3}$/.test(spec.viewBox ?? '')) {
    throw new Error(`Pose "${poseName}": "viewBox" must be four numbers like "0 0 512 640"`);
  }

  return spec.viewBox.trim().replace(/\s+/g, ' ');
}

function buildStill(library, poseName, spec) {
  const nodes = spec.layers.flatMap((layer) =>
    expandLayer(layer, library, poseName, spec, Boolean(spec.alternateFaces))
  );

  assertUniqueIds(nodes, `Pose "${poseName}"`);

  return serializeDocument({
    viewBox: readViewBox(poseName, spec),
    nodes,
    palette: library.palette,
  });
}

function buildAnimated(library, poseName, spec) {
  const animated = spec.animated ?? {};
  const cssFile = path.join(library.partsDir, 'animations', `${poseName}.css`);

  if (!fs.existsSync(cssFile)) {
    throw new Error(`Pose "${poseName}" has no ${relative(cssFile)}`);
  }

  let nodes = spec.layers.flatMap((layer) =>
    expandLayer(layer, library, poseName, spec, Boolean(animated.alternateFaces))
  );

  if (animated.upper) {
    nodes = groupRun(nodes, 'upper', animated.upper, poseName);
  }

  nodes = [{ tag: 'g', id: IDLE_GROUP_ID, children: nodes }];
  assertUniqueIds(nodes, `Pose "${poseName}" (animated)`);

  return serializeDocument({
    viewBox: readViewBox(poseName, spec),
    nodes,
    palette: library.palette,
    extraCss: fs.readFileSync(cssFile, 'utf8').trim(),
  });
}

/** Every generated file's absolute path and contents, without writing anything. */
function generateAll({
  partsDir = PARTS_DIR,
  stillDir = STILL_DIR,
  animatedDir = ANIMATED_DIR,
} = {}) {
  const library = loadLibrary(partsDir);
  const files = {};

  for (const [poseName, spec] of Object.entries(library.manifest.poses)) {
    if (!/^[a-z0-9-]+$/.test(poseName) || !Array.isArray(spec.layers) || !spec.layers.length) {
      throw new Error(`Pose "${poseName}" needs a plain name and a non-empty "layers" list`);
    }

    files[path.join(stillDir, `loggy-${poseName}.svg`)] = buildStill(library, poseName, spec);
    files[path.join(animatedDir, `loggy-${poseName}.svg`)] = buildAnimated(library, poseName, spec);
  }

  return files;
}

/** Pose SVGs on disk that the manifest no longer produces (a removed or renamed pose). */
function findStale(generated, dirs = [STILL_DIR, ANIMATED_DIR]) {
  return dirs.flatMap((dir) =>
    fs.existsSync(dir)
      ? fs
          .readdirSync(dir)
          .filter((name) => /^loggy-.*\.svg$/.test(name))
          .map((name) => path.join(dir, name))
          .filter((file) => !(file in generated))
      : []
  );
}

function main() {
  const check = process.argv.includes('--check');
  const generated = generateAll();
  const stale = findStale(generated);
  const changed = Object.entries(generated).filter(
    ([file, contents]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents
  );

  if (stale.length) {
    console.error(
      `Not in poses.json any more (delete or restore): ${stale.map(relative).join(', ')}`
    );
  }

  if (check) {
    for (const [file] of changed) {
      console.error(`out of date: ${relative(file)}`);
    }

    process.exit(changed.length || stale.length ? 1 : 0);
  }

  for (const [file, contents] of changed) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, contents);
    console.log(`wrote ${relative(file)} (${contents.length} bytes)`);
  }

  console.log(
    changed.length
      ? `${changed.length} of ${Object.keys(generated).length} files changed`
      : `all ${Object.keys(generated).length} files already up to date`
  );

  if (stale.length) {
    process.exit(1);
  }
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}

