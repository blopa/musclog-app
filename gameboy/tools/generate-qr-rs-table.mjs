// Generate the fixed QR version 11-L Reed-Solomon product table used by the
// cartridge encoder. The QR generator always uses the same degree-30 divisor,
// so doing this multiplication at build time saves thousands of slow GF(256)
// operations for every displayed frame.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = fileURLToPath(new URL('.', import.meta.url));
const outputPath = join(toolsDir, '..', 'src', 'features', 'optical', 'qr_rs_products.generated.h');
const degree = 30;

function multiply(left, right) {
  let x = left;
  let y = right;
  let result = 0;
  for (let bit = 0; bit !== 8; bit++) {
    result = ((result << 1) ^ ((result & 0x80) === 0 ? 0 : 0x11d)) & 0xff;
    if ((y & 0x80) !== 0) result ^= x;
    y = (y << 1) & 0xff;
  }
  return result;
}

function divisorCoefficients() {
  const result = new Uint8Array(degree);
  result[degree - 1] = 1;
  let root = 1;
  for (let i = 0; i !== degree; i++) {
    for (let j = 0; j !== degree; j++) {
      result[j] = multiply(result[j], root);
      if (j + 1 < degree) result[j] ^= result[j + 1];
    }
    root = multiply(root, 2);
  }
  return result;
}

const divisor = divisorCoefficients();
const products = [];
for (let factor = 0; factor !== 256; factor++) {
  for (const coefficient of divisor) products.push(multiply(coefficient, factor));
}

const rows = [];
for (let offset = 0; offset !== products.length; offset += 16) {
  rows.push(
    `    ${products
      .slice(offset, offset + 16)
      .map((value) => `0x${value.toString(16).padStart(2, '0')}u`)
      .join(', ')},`
  );
}

writeFileSync(
  outputPath,
  `/* Generated by gameboy/tools/generate-qr-rs-table.mjs. Do not edit. */
#ifndef MUSCLOG_QR_RS_PRODUCTS_GENERATED_H
#define MUSCLOG_QR_RS_PRODUCTS_GENERATED_H

#define QR_RS_DEGREE ${degree}u

/* Row N contains divisor[0..29] multiplied by GF(256) factor N. */
static const uint8_t qr_rs_products[256u * QR_RS_DEGREE] = {
${rows.join('\n')}
};

#endif /* MUSCLOG_QR_RS_PRODUCTS_GENERATED_H */
`
);
