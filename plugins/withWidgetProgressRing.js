const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

// expo-widgets draws a determinate CircularProgressIndicator with peek-glance's
// `peek_determinate_circular_progress` layout and drawable: a ProgressBar fixed at 32dp (Glance
// sizes only the frame it is dropped into, so a `size` modifier never reaches it), drawing a thick
// ring whose progress starts at 3 o'clock; the widget runtime also ignores `strokeWidth`. App
// resources of the same name win the resource merge, so these restyle every widget ring to match
// the iOS gauge: filling its box, thin, starting at 12 o'clock. The ring's colors are still tinted
// at runtime from the snapshot palette.
const RESOURCE_NAME = 'peek_determinate_circular_progress';
// For a `ring` shape, inner radius = width / innerRadiusRatio and thickness = width /
// thicknessRatio; 2 / 2.4 + 2 / 12 = 1, so the outer edge touches the box.
const THICKNESS_RATIO = 12;
const INNER_RADIUS_RATIO = 2.4;

function ringShape(useLevel, color) {
  return `<shape
            android:shape="ring"
            android:innerRadiusRatio="${INNER_RADIUS_RATIO}"
            android:thicknessRatio="${THICKNESS_RATIO}"
            android:useLevel="${useLevel}">
            <solid android:color="${color}" />
        </shape>`;
}

function progressRingDrawable() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withWidgetProgressRing.js; overrides peek-glance's drawable. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:id="@android:id/background">
        ${ringShape(false, '#33000000')}
    </item>
    <item android:id="@android:id/progress">
        <rotate
            android:fromDegrees="-90"
            android:pivotX="50%"
            android:pivotY="50%"
            android:toDegrees="-90">
            ${ringShape(true, '#FF6750A4')}
        </rotate>
    </item>
</layer-list>
`;
}

// Keeps peek-glance's view id, which its RemoteViews code addresses.
function progressRingLayout() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withWidgetProgressRing.js; overrides peek-glance's layout. -->
<ProgressBar xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/peek_progress"
    style="?android:attr/progressBarStyleHorizontal"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:indeterminate="false"
    android:indeterminateOnly="false"
    android:max="100"
    android:progress="0"
    android:progressDrawable="@drawable/${RESOURCE_NAME}" />
`;
}

// Paths are relative to the native app module.
const RESOURCES = {
  [`src/main/res/drawable/${RESOURCE_NAME}.xml`]: progressRingDrawable,
  [`src/main/res/layout/${RESOURCE_NAME}.xml`]: progressRingLayout,
};

module.exports = function withWidgetProgressRing(config) {
  return withDangerousMod(config, [
    'android',
    (mod) => {
      for (const [file, render] of Object.entries(RESOURCES)) {
        const target = path.join(mod.modRequest.platformProjectRoot, 'app', file);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, render());
      }

      return mod;
    },
  ]);
};

module.exports.RESOURCES = RESOURCES;
module.exports.progressRingDrawable = progressRingDrawable;
