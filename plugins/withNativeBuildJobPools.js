/**
 * WHY THIS PLUGIN EXISTS
 *
 * A release build compiles every CMake module (Skia, Reanimated, Worklets,
 * VisionCamera, ...) for four ABIs. Gradle's `org.gradle.workers.max` only
 * limits how many of those tasks run at once — each task still starts its own
 * `ninja`, which runs one clang per CPU. Skia's translation units pull in the
 * whole Skia header tree and take over a gigabyte each, so on the free EAS
 * Android worker the OS OOM-killed the Gradle daemon mid-build ("Gradle build
 * daemon disappeared unexpectedly"). A bigger worker needs a paid EAS plan.
 *
 * Ninja job pools cap compile and link jobs per CMake project instead, and
 * `CMAKE_JOB_POOLS` is honoured by every CMakeLists without patching it. The
 * arguments are added when the Android plugin is applied, i.e. before each
 * module's own `android {}` block, which appends its arguments after ours.
 * The block must sit ABOVE `apply plugin: "com.facebook.react.rootproject"`:
 * that plugin evaluates `:app` immediately, so a block below it would arrive
 * after `:app` had already been configured.
 */

const { withProjectBuildGradle } = require('expo/config-plugins');

const MARKER = '// @musclog native-build-job-pools';

const COMPILE_JOBS = 2;
const LINK_JOBS = 1;

const BLOCK = `${MARKER}
// Caps clang/ld parallelism per CMake project so release builds fit in the
// free EAS worker's RAM. Generated by plugins/withNativeBuildJobPools.js.
subprojects { subproject ->
  ['com.android.application', 'com.android.library'].each { pluginId ->
    subproject.plugins.withId(pluginId) {
      subproject.android.defaultConfig.externalNativeBuild.cmake.arguments(
        '-DCMAKE_JOB_POOLS=compile=${COMPILE_JOBS};link=${LINK_JOBS}',
        '-DCMAKE_JOB_POOL_COMPILE=compile',
        '-DCMAKE_JOB_POOL_LINK=link'
      )
    }
  }
}
`;

const ANCHOR = 'apply plugin: "expo-root-project"';

function addJobPools(contents) {
  if (contents.includes(MARKER)) {
    return contents;
  }

  if (!contents.includes(ANCHOR)) {
    throw new Error(`withNativeBuildJobPools: could not find '${ANCHOR}' in android/build.gradle`);
  }

  return contents.replace(ANCHOR, `${BLOCK}\n${ANCHOR}`);
}

function withNativeBuildJobPools(config) {
  return withProjectBuildGradle(config, (gradleConfig) => {
    gradleConfig.modResults.contents = addJobPools(gradleConfig.modResults.contents);
    return gradleConfig;
  });
}

module.exports = withNativeBuildJobPools;
module.exports.addJobPools = addJobPools;
