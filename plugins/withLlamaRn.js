/**
 * Runs llama.rn's own config plugin (iOS memory entitlements on production builds), then trims
 * the Android native libraries llama.rn packages.
 *
 * llama.rn ships that plugin as an ES module, so it is required when the plugin runs, not when it
 * is named in `app.json`. Under Jest the plugin list is still run (`metro.config.js` reads the Expo
 * config), but ESM from `node_modules` does not load there and no native file is written, so the
 * plugin is skipped; a real prebuild or EAS build is not under Jest.
 *
 * WHY THE TRIM EXISTS
 *
 * llama.rn ships llama.cpp once per ARM CPU generation and picks one at runtime
 * (`RNLlama.loadNative`: hexagon+opencl, then dotprod+i8mm, dotprod, i8mm, fp16 (`v8_2`), plain
 * `v8`). Packaging all of them made 2.18.0 about 31 MB bigger to download than 2.17.x. The loader
 * catches the `UnsatisfiedLinkError` of a missing variant and tries the next one, so leaving a
 * variant out only changes which build a phone runs. We leave out three that cost nothing:
 *  - `v8_2_dotprod_i8mm_hexagon_opencl` (the biggest, 12 MB): the `dotprod_i8mm` CPU code plus the
 *    Hexagon NPU and OpenCL GPU backends. Android loads models with `n_gpu_layers: 0`
 *    (`services/localModels/llamaRuntime.ts`), so nothing is ever offloaded and those Snapdragon
 *    phones run `v8_2_dotprod_i8mm` instead, the same CPU code. Its Hexagon helper libraries, which
 *    llama.rn copies into the app's assets on every build (`syncRNLlamaHtpAssets`), go too.
 *  - `v8_2_i8mm`: i8mm without dot product, which no shipping ARM core has.
 *  - `v8_2`: fp16 without dot product, a handful of 2017-2018 chips; they now run plain `v8`.
 * Kept: the generic `rnllama` (always loaded) and `rnllama_jni`, `v8` (every 64-bit ARM phone),
 * `v8_2_dotprod` (Cortex-A55/A75 to A78: about 2018-2022 and today's mid-range) and
 * `v8_2_dotprod_i8mm` (ARMv9 cores: 2022 on), plus x86_64 (emulators, Chromebooks; Play never
 * sends it to a phone).
 */

const { withAppBuildGradle } = require('expo/config-plugins');

const MARKER = '// @musclog llama-rn-slim';

const DROPPED_VARIANTS = ['v8_2', 'v8_2_i8mm', 'v8_2_dotprod_i8mm_hexagon_opencl'];

// Each variant is a prebuilt llama.cpp core plus the JNI wrapper CMake builds against it.
const DROPPED_LIBRARIES = DROPPED_VARIANTS.flatMap((variant) => [
  `librnllama_${variant}.so`,
  `librnllama_jni_${variant}.so`,
]);

const HTP_ASSETS_DIR = 'src/main/assets/ggml-hexagon';

const BLOCK = `${MARKER}
// Leaves out llama.rn CPU variants and Hexagon assets the app never uses.
// Generated by plugins/withLlamaRn.js; the reasons are written there.
android {
    packagingOptions {
        jniLibs {
            excludes += [
${DROPPED_LIBRARIES.map((name) => `                "**/${name}",`).join('\n')}
            ]
        }
    }
}

tasks.matching { it.name == "syncRNLlamaHtpAssets" }.configureEach {
    enabled = false
}

tasks.matching { it.name == "preBuild" }.configureEach {
    doFirst {
        delete(file("${HTP_ASSETS_DIR}"))
    }
}
`;

function addLlamaRnSlimming(buildGradle) {
  if (buildGradle.includes(MARKER)) {
    return buildGradle;
  }

  return `${buildGradle.trimEnd()}\n\n${BLOCK}`;
}

function withLlamaRn(config, props) {
  const slimmed = withAppBuildGradle(config, (gradleConfig) => {
    gradleConfig.modResults.contents = addLlamaRnSlimming(gradleConfig.modResults.contents);

    return gradleConfig;
  });

  if (process.env.JEST_WORKER_ID) {
    return slimmed;
  }

  const loaded = require('llama.rn/app.plugin.js');
  const plugin = loaded.default ?? loaded;

  return plugin(slimmed, props);
}

module.exports = withLlamaRn;
module.exports.addLlamaRnSlimming = addLlamaRnSlimming;
module.exports.DROPPED_LIBRARIES = DROPPED_LIBRARIES;
